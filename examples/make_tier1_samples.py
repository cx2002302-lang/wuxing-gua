# -*- coding: utf-8 -*-
"""
make_tier1_samples.py -- deterministic generator for the tier-1 teaching samples

Writes two files next to this script (byte-identical on every re-run; nothing
random, no clock, no locale dependence):

  tier1_starter_model.json       the 8-state "cube climber" teaching model
  tier1_xor_goalswap_group.json  a 2-element candidate group for the SAME model
                                 that looks legal on the arrow diagram but is
                                 not -- the runnable refusal demo

This is a hand-constructed teaching model, NOT a transcription of a real
system (the three real case studies in this directory keep their own
provenance). The construction rule is fully stated here and in
examples/README.md, so every number the tool prints on these files can be
checked by hand on the cube diagram:

  states    = the 8 vertices of a cube, numbered as 3-bit strings 000..111
  actions   = 0,1,2 -- "flip bit a", deterministic (p = 1.0)
  goal      = 111 (state 7): absorbing -- every action self-loops, reward 0
  reward    = +1 if the flip goes UP one level (popcount +1),
              -1 if it goes DOWN one level (popcount -1)

The symmetry a reader can see on the paper cube: the 6 rotations around the
long diagonal through 000 and 111 (all ways to permute the three axes).
The refusal candidate: XOR-by-001, the permutation pairing every vertex with
its neighbour along the bit-0 axis -- it swaps the goal corner 7 with 6.

Usage (from the repository root or anywhere):

  python -X utf8 examples/make_tier1_samples.py            # write both files
  python -X utf8 examples/make_tier1_samples.py --out DIR  # write into DIR
  python -X utf8 examples/make_tier1_samples.py --check    # verify byte-identity

`--check` regenerates both files in memory and compares against the committed
copies, exiting 0 when byte-identical (used when editing the samples).
"""
import argparse
import json
import os
import sys

N_BITS = 3
N_ACTIONS = 3
N_STATES = 1 << N_BITS          # 8
GOAL = N_STATES - 1             # 111 = state 7, absorbing


def _popcount(x):
    return bin(x).count("1")


def build_model():
    """Cube climber model as the wuxing_gua model.json input format."""
    trans = []
    for s in range(N_STATES):
        row = []
        for a in range(N_ACTIONS):
            if s == GOAL:
                row.append([[1.0, GOAL, 0.0]])
            else:
                u = s ^ (1 << a)
                r = 1.0 if _popcount(u) > _popcount(s) else -1.0
                row.append([[1.0, u, r]])
        trans.append(row)
    return {
        "n_bits": N_BITS,
        "n_actions": N_ACTIONS,
        "n_states": N_STATES,
        "goals": [GOAL],
        "meta": {
            "source_system": ("tier-1 teaching model: cube climber "
                              "(hand-constructed for this repository, "
                              "not transcribed from a real system)"),
            "variant": "starter",
            "construction": ("state = 3-bit cube vertex; action a = flip bit a "
                             "(deterministic p=1.0); goal 111 absorbing "
                             "(self-loop, reward 0); reward +1 up one level "
                             "(popcount+1), -1 down one level (popcount-1)"),
            "visible_symmetry": ("6 rotations around the long diagonal 000-111 "
                                 "(all permutations of the three axes)"),
            "regenerate": "python -X utf8 examples/make_tier1_samples.py",
        },
        "trans": trans,
    }


def build_xor_goalswap_group():
    """
    The refusal candidate: the order-2 group {id, XOR-by-001}.

    elements[i][s] = image of state s. The non-identity element pairs every
    vertex with its neighbour along the bit-0 axis, in particular swapping the
    absorbing goal corner 7 with 6. On the bare cube diagram it maps arrows to
    arrows, but the goal's three self-loop arrows become three arrows leaving
    vertex 6 -- `wuxing_gua check` certifies this and refuses (exit 1).
    """
    xor1 = [s ^ 1 for s in range(N_STATES)]
    ident = list(range(N_STATES))
    return {
        "n_states": N_STATES,
        "elements": [ident, xor1],
        "semantics": {"action": "relabel"},
        "meta": {
            "construction": ("order-2 group generated by XOR-by-001 "
                             "(s -> s^1): the 'swap the goal with its "
                             "neighbour' candidate; teaching sample for the "
                             "refusal path, expected to be REJECTED by check"),
            "why_it_looks_legal": ("on the cube without the goal marking it "
                                   "maps edges to edges (it is a symmetry of "
                                   "the bare cube graph)"),
            "semantics_note": ("declared relabel: the cube climber is a "
                               "switch-class model (action a = flip bit a), "
                               "the reading the refusal is certified under "
                               "(docs/judge-semantics.md)"),
            "regenerate": "python -X utf8 examples/make_tier1_samples.py",
        },
    }


def _dump(obj):
    return json.dumps(obj, ensure_ascii=False, indent=1) + "\n"


def main(argv=None):
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=here, help="target directory (default: this script's directory)")
    ap.add_argument("--check", action="store_true",
                    help="do not write; verify the committed files are byte-identical")
    args = ap.parse_args(argv)

    payloads = {
        "tier1_starter_model.json": _dump(build_model()),
        "tier1_xor_goalswap_group.json": _dump(build_xor_goalswap_group()),
    }
    if args.check:
        bad = []
        for name, blob in payloads.items():
            p = os.path.join(here, name)
            with open(p, "r", encoding="utf-8", newline="") as f:
                current = f.read()
            if current != blob:
                bad.append(name)
        if bad:
            sys.stderr.write("byte-identity FAILED: %s\n" % ", ".join(bad))
            return 1
        sys.stdout.write("byte-identity OK: %s\n" % ", ".join(sorted(payloads)))
        return 0

    os.makedirs(args.out, exist_ok=True)
    for name, blob in payloads.items():
        p = os.path.join(args.out, name)
        with open(p, "w", encoding="utf-8", newline="") as f:
            f.write(blob)
        sys.stdout.write("wrote %s (%d bytes)\n" % (p, len(blob.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
